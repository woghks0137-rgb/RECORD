function onYouTubeIframeAPIReady() {
    youtubePlayer = new YT.Player('youtubePlayer', {
        width: '200',
        height: '200',
        videoId: '',

        playerVars: {
            playsinline: 1,
            rel: 0
        },

        events: {
            onReady: function () {
                updatePlayButton();
            },

            onStateChange: onPlayerStateChange
        }
    });
}

function onPlayerStateChange(event) {
    console.log('YouTube 상태:', event.data);

    if (event.data === YT.PlayerState.PLAYING) {
        isPlaying = true;
        updatePlayButton();
        startProgress();

    } else if (event.data === YT.PlayerState.PAUSED) {
        isPlaying = false;
        updatePlayButton();
        stopProgress();

    } else if (event.data === YT.PlayerState.ENDED) {
        isPlaying = false;
        updatePlayButton();
        stopProgress();
        nextMusic();
    }
}

function onYouTubeIframeAPIReady() {
    youtubePlayer = new YT.Player('youtubePlayer', {
        width: '200',
        height: '200',
        videoId: '',

        playerVars: {
            playsinline: 1,
            rel: 0
        },

        events: {
            onReady: function () {
                console.log('YouTube 준비 완료');
                updatePlayButton();
            },

            onStateChange: onPlayerStateChange,

            onError: function (event) {
                console.log('YouTube 오류 코드:', event.data);

                alert('이 노래는 재생할 수 없습니다.');
                isPlaying = false;
                updatePlayButton();
            }
        }
    });
}

function renderMusicList(year) {
    const list = musicData[year];

    musicList.innerHTML = list.map((music, index) => `
        <div class="music-item" data-index="${index}">
            <div class="music-item-left">
                <img src="${music.image}" alt="${music.title}">

                <div class="music-info">
                    <h3 class="main-text">${music.title}</h3>
                    <p class="sub-text">${music.artist}</p>
                </div>
            </div>

            <div class="music-item-right">
                <span class="sub-text">${music.year}</span>
                <span class="sub-text">${music.duration}</span>

                <button class="play-button" type="button">
                    <img src="${playIcon}" alt="재생버튼">
                </button>
            </div>
        </div>
    `).join('');

    musicList.querySelectorAll('.play-button').forEach(button => {
        button.addEventListener('click', function () {
            const musicItem = this.closest('.music-item');
            playMusic(Number(musicItem.dataset.index));
        });
    });
}

function playMusic(index) {
    const list = musicData[currentYear];
    const music = list[index];

    if (!music || !youtubePlayer) return;

    currentIndex = index;

    playerImage.src = music.image;
    playerImage.alt = music.title;

    musicImg.src = music.topImage;
    musicImg.alt = music.title;

    playerTitle.textContent = music.title;
    playerArtist.textContent = music.artist;

    playerYear.textContent = music.year;
    playerDuration.textContent = music.duration;

    currentTime.textContent = '00:00';
    duration.textContent = music.duration;

    progressBar.value = 0;

    musicPlayer.style.display = 'flex';

    musicInner.classList.add('player-active');

    youtubePlayer.loadVideoById(music.videoId);
}

function updatePlayButton() {
    const playImage = playBtn.querySelector('img');

    if (isPlaying) {
        playImage.src = pauseIcon;
        playImage.alt = '일시정지';

    } else {
        playImage.src = playIcon;
        playImage.alt = '재생';
    }
}

yearButtons.forEach(button => {
    button.addEventListener('click', function () {
        const year = this.dataset.year;

        if (youtubePlayer) {
            youtubePlayer.stopVideo();
        }

        stopProgress();
        isPlaying = false;

        currentYear = year;
        currentIndex = 0;

        yearButtons.forEach(btn => {
            btn.classList.remove('active');
        });

        this.classList.add('active');

        yearText.textContent = yearDescriptions[year];

        renderMusicList(year);
        updatePlayButton();
    });
});

playBtn.addEventListener('click', function () {
    if (!youtubePlayer) return;

    const state = youtubePlayer.getPlayerState();

    if (state === YT.PlayerState.PLAYING) {
        youtubePlayer.pauseVideo();

    } else {
        youtubePlayer.playVideo();
    }
});

backBtn.addEventListener('click', function () {
    const list = musicData[currentYear];

    currentIndex--;

    if (currentIndex < 0) {
        currentIndex = list.length - 1;
    }

    playMusic(currentIndex);
});

nextBtn.addEventListener('click', nextMusic);

function nextMusic() {
    const list = musicData[currentYear];

    currentIndex++;

    if (currentIndex >= list.length) {
        currentIndex = 0;
    }

    playMusic(currentIndex);
}

closeBtn.addEventListener('click', function () {
    if (youtubePlayer) {
        youtubePlayer.stopVideo();
    }

    stopProgress();
    isPlaying = false;

    musicPlayer.style.display = 'none';

    musicInner.classList.remove('player-active');

    progressBar.value = 0;
    currentTime.textContent = '00:00';

    updatePlayButton();
});

function startProgress() {
    stopProgress();

    progressTimer = setInterval(function () {
        if (!youtubePlayer) return;

        const current = youtubePlayer.getCurrentTime();
        const total = youtubePlayer.getDuration();

        if (!total) return;

        currentTime.textContent = formatTime(current);
        duration.textContent = formatTime(total);

        progressBar.value = (current / total) * 100;

    }, 500);
}

function stopProgress() {
    if (progressTimer) {
        clearInterval(progressTimer);
        progressTimer = null;
    }
}

progressBar.addEventListener('input', function () {
    if (!youtubePlayer) return;

    const total = youtubePlayer.getDuration();

    if (!total) return;

    youtubePlayer.seekTo(
        (this.value / 100) * total,
        true
    );
});

function formatTime(time) {
    const minutes = Math.floor(time / 60);
    const seconds = Math.floor(time % 60);

    return `${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}`;
}

